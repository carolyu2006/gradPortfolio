        <p class="statement"><span class="statement-label">Research question</span>Can a designer's tacit sense of
            “on brand” be written down as rules an AI agent can follow?</p>

        <section id="abstract">
            <h2>Abstract</h2>
            <p class="lead">“Make it look better” cannot guide an agent. Visual quality becomes repeatable only when
                taste is translated into concrete constraints.</p>
            <figure class="figure-float">
                <img src="/assets/images/projects/ai-brand-kit/kv-02.webp" alt="Generated Life Services key visual">
                <figcaption>A Life Services key visual generated by the workflow.</figcaption>
            </figure>
            <p>TikTok Life Services operations teams can generate campaign pages on an internal agent platform, but
                the output is often generic and off-brand. I compared two ways of teaching the agent the brand — a
                fine-tuned LoRA and a written skill — and the skill produced better on-brand images. I then built a
                two-skill workflow that takes a campaign brief to a header image and a complete H5 page, and iterated
                on it by cataloguing how the output failed and encoding a fix for each failure.</p>
        </section>

        <section id="context">
            <h2>Context</h2>
            <p class="lead">Life Services teams need polished, on-brand campaign visuals and H5 pages, often and
                fast.</p>
            <p>Making each page by hand with designers is slow. The agent platform lets operations teams generate
                pages themselves, but the visual quality is inconsistent and rarely matches the brand. There are two
                broad ways to give a generative system a brand's style: adapt the model's weights (for example with a
                LoRA, Hu et al., 2021), or leave the model alone and write the style down as instructions, references,
                and scripts an agent follows step by step. The second keeps the rules readable and editable by
                designers — if it works.</p>
            <p>The goals were a <strong>higher baseline</strong> (output starts on-brand), <strong>wider
                adoption</strong> (operations teams stop queuing for design support), and <strong>faster
                turnaround</strong> (brief to page in one pass).</p>
        </section>

        <section id="method">
            <h2>Method</h2>
            <h3>01 — LoRA vs. skill</h3>
            <!-- TODO(research): describe the comparison — how many images per approach, what criteria (logo accuracy,
                 style match, text quality…), and who judged them. Even “12 images each, rated by 3 designers” is enough. -->
            <p>I generated header images with both approaches and compared them on image quality and fit with the Life
                Services visual style. The comparison <strong>favored the skill</strong>, which became the foundation
                for the rest of the workflow.</p>

            <h3>02 — From a linear chain to templates</h3>
            <p>The first workflow was a linear chain: campaign topic → generated prompt → generated image. It
                <strong>rarely met the quality bar</strong>, and the style repeated itself across campaigns. I replaced
                it with <strong>prompt templates organized by topic category</strong>: the skill classifies the
                campaign, picks the matching template, and composes a prompt from it.</p>
            <figure>
                <img src="/assets/images/projects/ai-brand-kit/prompt-canvas.webp" alt="Working canvas showing a logo reference and category reference images fanning out into prompt threads and their generated header images">
                <figcaption>The working canvas: a logo reference and category references fanning out into prompt
                    threads and their generated header images.</figcaption>
            </figure>

            <h3>03 — Failure-driven iteration</h3>
            <p>I tested the agent round by round, recorded each recurring failure, and changed the reference inputs,
                prompts, scripts, or skill steps to address it — working with developers on specific issues such as
                removing the background behind a generated title.</p>

            <h3>04 — Encoding the H5 page</h3>
            <p>I analyzed sample H5 pages to decide which parts of the layout could be <strong>encoded as a
                skill</strong>, then defined a template for each page section, with the HTML and CSS knowledge needed to
                reproduce them consistently — including a typographic treatment that keeps section subtitles on
                brand.</p>
        </section>

        <section id="system">
            <h2>System</h2>
            <p class="lead">Two skills: one for the header image, one for the H5 page built from it.</p>

            <h3>Skill 01 — Header image generation</h3>
            <p>Turns a campaign theme into a ready-to-use Life Services key visual. The SKILL.md steps:</p>
            <ol>
                <li>Define the campaign theme</li>
                <li>Classify it into one of seven categories</li>
                <li>Draft three titles, pick one</li>
                <li>Compose the prompt from the template</li>
                <li>Generate against two reference images</li>
                <li>Overlay the auto-coloured logo</li>
            </ol>
