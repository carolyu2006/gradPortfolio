        <section id="discussion">
            <h2>Discussion</h2>
            <h3>From taste to rules</h3>
            <p>References only became useful once they were translated into concrete visual, content, and layout
                constraints. Writing the skill was, in effect, making a designer's judgement explicit — and discovering
                which parts of it could not be written down.</p>
            <h3>Readable rules vs. trained weights</h3>
            <p>A skill can be read, reviewed, and edited by designers and operations staff; a LoRA cannot. That
                transparency may matter as much as image quality when a team has to maintain a brand over time.</p>
            <h3>Limitations</h3>
            <p>The workflow was tested on sample campaigns during a three-month internship. It has not yet been
                validated on real production requests with measurable quality feedback, and details are limited by
                confidentiality.</p>
        </section>

